#!/usr/bin/env bash
# Проверка диска DP в текущей модели.
#
# Исторический контроллер DP для машины 100-25 в доступных документах не найден.
# Ранее как временный вариант использовалась пара RH11/RP04 из simh, теперь
# основным прототипом стала пара RP11/RP02/RP03: она ближе к имени драйвера
# DP из RT-11 и к геометрии дисков. Файлы e10025_rh.c и e10025_rp.c остаются
# в сборке, но не регистрируются в sim_devices, чтобы не было конфликта по
# адресу 016700 и вектору 0254.
set -u
here=$(cd "$(dirname "$0")/.." && pwd)
if [ ! -x "$here/tests/test_rp03_disk.sh" ]; then
  echo "FAIL: no test_rp03_disk.sh" >&2
  exit 1
  fi
exec bash "$here/tests/test_rp03_disk.sh"
